/**
 * Какая это сборка интерфейса. Одна кодовая база — три сборки:
 * - мокап (`npm run dev`, `build`, `build:single`): имитация, панель «Демо-сценарий»;
 * - расширение (`ext:build`): боковая панель и вкладка, поиск по выделенному тексту;
 * - веб-версия (`npm run build:web` → dist-web/, адрес `/app/` на сервере): та же панель
 *   во вкладке, данные — наш сервер на том же адресе; без панели «Демо-сценарий», без
 *   демо-данных и без функций «по выделенному тексту» (они есть только в расширении).
 */
export const IS_WEB_BUILD = import.meta.env.VITE_TARGET === 'web';

/**
 * Показывать ли функции «по выделенному тексту» (контекстное меню, демо-страница СМИ).
 * В веб-версии выделять текст на чужой странице нечем.
 */
export const SELECTION_FEATURES = !IS_WEB_BUILD;
