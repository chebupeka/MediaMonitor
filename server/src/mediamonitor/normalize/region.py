@dataclass(frozen=True)
class _Place:
    name: str
    pattern: re.Pattern[str]


def _compile() -> list[_Place]:
    places = [
        _Place(f"{adjective} район", re.compile(rf"(?<![\w-]){stem}(?:ий|ого|ому|ом)\s+район"))
        for adjective, stem in _DISTRICT_STEMS.items()
    ]
    places += [_Place(name, re.compile(rf"(?<![\w-]){pattern}")) for name, pattern in _PLACES]
    return places


_COMPILED = _compile()


def find_places(*texts: str | None) -> list[str]:
    """Места края в текстах, в порядке первого упоминания, без повторов."""
    hay = " \n ".join(t for t in texts if t).lower().replace("ё", "е")
    if not hay:
        return []
    found: list[tuple[int, str]] = []
    covered: list[tuple[int, int]] = []
    for place in _COMPILED:
        for match in place.pattern.finditer(hay):
            # «Канский район» уже найден — «Канск» внутри него не считаем отдельно.
            if any(a <= match.start() < b for a, b in covered):
                continue
            covered.append((match.start(), match.end()))
            found.append((match.start(), place.name))
            break
    found.sort()
    result: list[str] = []
    for _, name in found:
        if name not in result:
            result.append(name)
    return result
